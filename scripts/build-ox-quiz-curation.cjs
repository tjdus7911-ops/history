const fs=require('fs');
const path=require('path');

const ROOT=path.resolve(__dirname,'..');
const SOURCE_DIR=path.join(ROOT,'docs','ox-quiz-curation');
const OUTPUT=path.join(ROOT,'dist','ox-quiz-curation.js');
const ERA_COUNTS={prehistoric:100,kingdoms:120,goryeo:120,joseon:150,empire:100,occupation:120,republic:100};
const BANNED_STATEMENT=/(?:다음 설명에 해당하는 역사 용어|이 문장이 (?:직접 )?설명하는 핵심 개념|위 설명은 .+로 분류|이 내용의 학습 주제|→|\?)/;
const BANNED_EXPLANATION=/(?:이 사실은 당시의 역사적 배경을 보여 줍니다|이는 .+의 특징입니다|위 설명은 올바른 역사적 사실입니다|제시된 답이 틀렸고 올바른 답은)/;
const normalize=value=>String(value||'').normalize('NFKC').replace(/[\s.,!?·'"“”‘’():;~\-『』〈〉《》]/g,'');
const sentenceCount=value=>(String(value).match(/[.!?](?=\s|$)/g)||[]).length;
const tokens=value=>(String(value).match(/[가-힣A-Za-z0-9·]+/g)||[]).map(token=>token.replace(/[은는이가을를의에에서와과로으로도만부터까지께서]+$/,'')).filter(token=>token.length>=2);

function fail(message){throw new Error(`OX curation: ${message}`)}
function loadEra(eraId,count){
 const file=path.join(SOURCE_DIR,`${eraId}.json`);
 if(!fs.existsSync(file))fail(`missing ${path.relative(ROOT,file)}`);
 let rows;
 try{rows=JSON.parse(fs.readFileSync(file,'utf8'))}catch(error){fail(`${eraId}.json is not valid JSON: ${error.message}`)}
 if(!Array.isArray(rows)||rows.length!==count)fail(`${eraId} must contain ${count} rows (actual ${Array.isArray(rows)?rows.length:'not an array'})`);
 const ids=new Set(),statements=new Set(),explanations=new Set();
 rows.forEach((row,index)=>{
  const expectedId=`ox-${eraId}-${String(index+1).padStart(3,'0')}`;
  if(!row||Object.keys(row).sort().join(',')!=='answer,explanation,id,statement')fail(`${expectedId} must use only id, statement, answer, explanation`);
  if(row.id!==expectedId)fail(`${eraId} row ${index+1} must be ${expectedId} (actual ${row.id})`);
  if(ids.has(row.id))fail(`duplicate id ${row.id}`);ids.add(row.id);
  if(typeof row.answer!=='boolean')fail(`${row.id} answer must be a historically reviewed Boolean`);
  if(typeof row.statement!=='string'||row.statement.length<12||!/\.$/.test(row.statement))fail(`${row.id} needs a complete declarative statement`);
  if(BANNED_STATEMENT.test(row.statement))fail(`${row.id} contains a question, arrow, or classification template`);
  if(sentenceCount(row.statement)!==1)fail(`${row.id} must test one declarative sentence`);
  const statementKey=normalize(row.statement);
  if(statements.has(statementKey))fail(`${row.id} duplicates another statement in ${eraId}`);statements.add(statementKey);
  if(typeof row.explanation!=='string'||/^[OX]입니다\./.test(row.explanation))fail(`${row.id} explanation must contain only the learning explanation; the runtime adds the answer label`);
  const explanationSentences=sentenceCount(row.explanation);
  if(explanationSentences<2||explanationSentences>4)fail(`${row.id} explanation must contain 2-4 sentences (actual ${explanationSentences})`);
  if(BANNED_EXPLANATION.test(row.explanation))fail(`${row.id} uses a banned generic explanation`);
  if(!row.answer&&!/틀|아니|잘못|반대/.test(row.explanation))fail(`${row.id} is X but does not identify the incorrect part`);
  const explanationKey=normalize(row.explanation),statementBody=normalize(row.statement);
  if(explanationKey===statementBody||explanationKey.startsWith(statementBody))fail(`${row.id} explanation merely repeats the statement`);
  const statementTokens=new Set(tokens(row.statement)),newTokens=new Set(tokens(row.explanation).filter(token=>!statementTokens.has(token)));
  if(newTokens.size<5)fail(`${row.id} explanation must add historical context or a judging basis (new tokens ${newTokens.size}/5)`);
  if(explanations.has(explanationKey))fail(`${row.id} duplicates another explanation in ${eraId}`);explanations.add(explanationKey);
 });
 return rows;
}

const eras={},all=[];
for(const [eraId,count] of Object.entries(ERA_COUNTS)){const rows=loadEra(eraId,count);eras[eraId]=rows;all.push(...rows)}
const allStatements=new Set(),allExplanations=new Set();
for(const row of all){const statement=normalize(row.statement),explanation=normalize(row.explanation);if(allStatements.has(statement))fail(`cross-era duplicate statement: ${row.id}`);if(allExplanations.has(explanation))fail(`cross-era duplicate explanation: ${row.id}`);allStatements.add(statement);allExplanations.add(explanation)}

const report={questionCount:all.length,eraCounts:Object.fromEntries(Object.entries(eras).map(([eraId,rows])=>[eraId,rows.length])),answerBalance:{o:all.filter(row=>row.answer).length,x:all.filter(row=>!row.answer).length},declarativeStatementCount:all.filter(row=>!row.statement.includes('?')).length,explanationSentenceRange:[Math.min(...all.map(row=>sentenceCount(row.explanation))),Math.max(...all.map(row=>sentenceCount(row.explanation)))],genericTemplateCount:all.filter(row=>BANNED_STATEMENT.test(row.statement)||BANNED_EXPLANATION.test(row.explanation)).length};
const output=`/* Generated by scripts/build-ox-quiz-curation.cjs from reviewed source files. */\n(function(){\nconst eras=${JSON.stringify(eras,null,2)};\nglobalThis.OX_QUIZ_CURATION=Object.freeze(Object.values(eras).flat());\nglobalThis.OX_CURATION_REPORT=Object.freeze(${JSON.stringify(report)});\n})();\n`;
if(process.argv.includes('--check')){
 if(!fs.existsSync(OUTPUT)||fs.readFileSync(OUTPUT,'utf8')!==output)fail('dist/ox-quiz-curation.js is stale; run node scripts/build-ox-quiz-curation.cjs');
 console.log(`PASS: ${report.questionCount} reviewed OX questions are valid and generated output is current.`);
}else{
 fs.writeFileSync(OUTPUT,output);
 console.log(`WROTE: ${path.relative(ROOT,OUTPUT)} (${report.questionCount} reviewed questions)`);
}
